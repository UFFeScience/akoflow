package main

import (
	"encoding/csv"
	"fmt"
	"math"
	"os"
	"path/filepath"
	"sort"
	"strconv"
	"strings"
)

type executionTableRow struct {
	cohort, environment, algorithm, runID, recovered, shared string
	planned, simulated, real, delta, errorPercent            float64
}

func readExecutionCSV(path string) ([]map[string]string, error) {
	f, err := os.Open(path)
	if err != nil {
		return nil, err
	}
	defer f.Close()
	rows, err := csv.NewReader(f).ReadAll()
	if err != nil || len(rows) < 2 {
		return nil, fmt.Errorf("invalid execution CSV %s: %v", path, err)
	}
	result := []map[string]string{}
	for _, row := range rows[1:] {
		values := map[string]string{}
		for i, key := range rows[0] {
			values[key] = row[i]
		}
		result = append(result, values)
	}
	return result, nil
}

func exportExecutionTable(root, historicalPath string) error {
	current, err := readExecutionCSV(filepath.Join(root, "all-execution-results.csv"))
	if err != nil {
		return err
	}
	historical, err := readExecutionCSV(historicalPath)
	if err != nil {
		return err
	}
	rows := []executionTableRow{}
	seen := map[string]bool{}
	add := func(cohort, environment, algorithm, runID, recovered, shared, p, s, r string) error {
		key := cohort + "/" + environment + "/" + algorithm
		if seen[key] || environment == "" || algorithm == "" || runID == "" {
			return fmt.Errorf("duplicate or incomplete execution %s", key)
		}
		seen[key] = true
		values := []float64{}
		for _, raw := range []string{p, s, r} {
			n, err := strconv.ParseFloat(raw, 64)
			if err != nil || n <= 0 || math.IsNaN(n) || math.IsInf(n, 0) {
				return fmt.Errorf("invalid duration in %s", key)
			}
			values = append(values, n)
		}
		rows = append(rows, executionTableRow{cohort, environment, algorithm, runID, recovered, shared, values[0], values[1], values[2], values[2] - values[1], 100 * math.Abs(values[1]-values[2]) / values[2]})
		return nil
	}
	for _, row := range current {
		algorithm := row["algorithm"]
		if algorithm == "moheft" {
			algorithm += "-" + row["objective"]
		}
		if row["completed_activities"] != "58" {
			return fmt.Errorf("incomplete execution %s", row["real_run_id"])
		}
		if err := add("current", row["environment"], algorithm, row["real_run_id"], "false", row["shared_real_observation"], row["planned_makespan_seconds"], row["simulated_makespan_seconds"], row["real_makespan_seconds"]); err != nil {
			return err
		}
	}
	for _, row := range historical {
		environment := map[string]string{"HPC": "hpc", "HPC + micro": "micro", "HPC + medium": "medium"}[row["scenario"]]
		recovered := strings.ToLower(row["recovered"])
		if err := add("historical-separate-campaign", environment, "prism-time", row["runId"], recovered, "", row["planned"], row["simulated"], row["real"]); err != nil {
			return err
		}
	}
	order := map[string]int{"current": 0, "historical-separate-campaign": 1, "hpc": 0, "micro": 1, "medium": 2, "heft": 0, "moheft-time": 1, "moheft-cost": 2, "prism-time": 3}
	sort.SliceStable(rows, func(i, j int) bool {
		a, b := rows[i], rows[j]
		if a.cohort != b.cohort {
			return order[a.cohort] < order[b.cohort]
		}
		if a.environment != b.environment {
			return order[a.environment] < order[b.environment]
		}
		return order[a.algorithm] < order[b.algorithm]
	})
	f, err := os.Create(filepath.Join(root, "execution-table.csv"))
	if err != nil {
		return err
	}
	defer f.Close()
	w := csv.NewWriter(f)
	if err := w.Write([]string{"cohort", "environment", "algorithm", "planned_seconds", "simulated_seconds", "real_seconds", "real_minus_simulated_seconds", "simulation_absolute_error_percent", "real_run_id", "recovered", "shared_observation"}); err != nil {
		return err
	}
	var tex, markdown strings.Builder
	tex.WriteString("% Generated by montage-fig8 execution-table-export.\n\\begingroup\n\\color{magenta}\n\\begin{table*}[t]\n\\centering\n\\colorlet{scolor}{magenta}\n\\caption{\\textcolor{magenta}{Completed Montage 58 observations. P, S, and R are planned, simulated, and real makespans in seconds. Simulation absolute percentage error is $100|S-R|/R$, using the real value as denominator; $\\Delta=R-S$ is positive when simulation underestimates execution. Asterisks identify one shared HPC real observation, not three independent runs. Historical observations belong to a separate campaign; the dagger marks recovery.}}\n\\label{tab:montage58-execution-errors}\n\\small\n\\setlength{\\tabcolsep}{4pt}\n\\begin{tabular}{llrrrrr}\n\\toprule\nEnvironment & Algorithm & P (s) & S (s) & R (s) & $\\Delta$ (s) & Error (\\%) \\\\\n\\midrule\n")
	markdown.WriteString("| Cohort | Environment | Algorithm | Planned (s) | Simulated (s) | Real (s) | Real - simulated (s) | Error (%) |\n|---|---|---|---:|---:|---:|---:|---:|\n")
	for i, row := range rows {
		num := func(v float64) string { return strconv.FormatFloat(v, 'g', -1, 64) }
		if err := w.Write([]string{row.cohort, row.environment, row.algorithm, num(row.planned), num(row.simulated), num(row.real), num(row.delta), num(row.errorPercent), row.runID, row.recovered, row.shared}); err != nil {
			return err
		}
		if row.cohort != "current" && (i == 0 || rows[i-1].cohort == "current") {
			tex.WriteString("\\midrule\n\\multicolumn{7}{l}{Historical PRISM observations (separate campaign)} \\\\\n\\midrule\n")
		}
		environment := map[string]string{"hpc": "HPC", "micro": "HPC + micro", "medium": "HPC + medium"}[row.environment]
		algorithm := map[string]string{"heft": "HEFT", "moheft-time": "MOHEFT Time", "moheft-cost": "MOHEFT Cost", "prism-time": "PRISM Time"}[row.algorithm]
		marker := ""
		if row.cohort == "current" && row.environment == "hpc" {
			marker = "$^{*}$"
		}
		if row.recovered == "true" {
			marker += "$^{\\dagger}$"
		}
		fmt.Fprintf(&tex, "%s & %s%s & %.2f & %.2f & %.2f & %+.2f & %.2f \\\\\n", environment, algorithm, marker, row.planned, row.simulated, row.real, row.delta, row.errorPercent)
		fmt.Fprintf(&markdown, "| %s | %s | %s | %.2f | %.2f | %.2f | %+.2f | %.2f |\n", row.cohort, environment, algorithm, row.planned, row.simulated, row.real, row.delta, row.errorPercent)
	}
	w.Flush()
	if err := w.Error(); err != nil {
		return err
	}
	tex.WriteString("\\bottomrule\n\\end{tabular}\n\\end{table*}\n\\endgroup\n")
	if err := os.WriteFile(filepath.Join(root, "execution-table.tex"), []byte(tex.String()), 0600); err != nil {
		return err
	}
	return os.WriteFile(filepath.Join(root, "execution-table.md"), []byte(markdown.String()), 0600)
}
